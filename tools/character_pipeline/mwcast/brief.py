"""The casting brief, `brief.yaml` (step-26 §7.1; PIPELINE.md §3): what `check-characters` requires of a
directory that holds a brief and no records yet (stage 1, casting).

The brief is generated by `tools/character_pipeline/casting/cast_director.py` in its YAML subset: top-level
`key: value` lines, the nested blocks `casting:` and `sources:` (two-space indent), deeper continuation
lines, and comments. The casting director knows no attribute name (the population profile defines them),
so neither does this check. It requires the structural keys, the person's key equal to its directory, the
casting block's keys with an integer template version, and every `sources:` key to be a top-level key of
the brief. A malformed line, a duplicate key or a missing key is refused with the file and the line.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .records import RecordError

REQUIRED = ("person", "from", "casting", "sources")
CASTING_KEYS = ("world", "profile", "template_version", "seed", "attempt")
NESTED = ("casting", "sources")

_TOP = re.compile(r"([a-z_][a-z0-9_]*):(.*)")
_NESTED = re.compile(r"  ([a-z_][a-z0-9_]*):(.*)")


@dataclass(frozen=True)
class Brief:
    person: str
    world: str
    template_version: int
    attributes: tuple[str, ...]


def _value(text: str) -> str:
    """The scalar before a ` #` comment, unquoted."""
    head = text.split(" #", 1)[0].strip()
    if len(head) >= 2 and head[0] == head[-1] and head[0] in "'\"":
        return head[1:-1]
    return head


def parse_brief(path: Path, directory: str) -> Brief:
    """Validate the brief at `path` for the character directory named `directory`."""
    top: dict[str, str] = {}
    blocks: dict[str, dict[str, str]] = {name: {} for name in NESTED}
    current: str | None = None
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        where = f"{path}: line {number}"
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            match = _TOP.fullmatch(line)
            if match is None:
                raise RecordError(f"{where}: not a `key: value` line")
            key, rest = match.group(1), match.group(2)
            if key in top:
                raise RecordError(f"{where}: duplicate key `{key}`")
            top[key] = _value(rest)
            current = key if key in NESTED and not top[key] else None
            continue
        if current is None:
            raise RecordError(f"{where}: an indented line outside the `casting:` and `sources:` blocks")
        if line.startswith("    "):
            continue  # a continuation of the previous nested value
        match = _NESTED.fullmatch(line)
        if match is None:
            raise RecordError(f"{where}: not a `  key: value` line of `{current}:`")
        key = match.group(1)
        if key in blocks[current]:
            raise RecordError(f"{where}: duplicate key `{current}.{key}`")
        blocks[current][key] = _value(match.group(2))
    for key in REQUIRED:
        if key not in top:
            raise RecordError(f"{path}: missing key `{key}`")
    if top["person"] != directory:
        raise RecordError(f"{path}: `person` is `{top['person']}`, the directory is `{directory}`")
    if not (top["from"].startswith("[") and top["from"].endswith("]") and len(top["from"]) > 2):
        raise RecordError(f"{path}: `from` must be a non-empty list of person files")
    casting = blocks["casting"]
    for key in CASTING_KEYS:
        if key not in casting:
            raise RecordError(f"{path}: missing key `casting.{key}`")
    if not re.fullmatch(r"\d+", casting["template_version"]):
        raise RecordError(f"{path}: `casting.template_version` must be an integer")
    sources = blocks["sources"]
    if not sources:
        raise RecordError(f"{path}: `sources` is empty")
    for key in sources:
        if key not in top:
            raise RecordError(f"{path}: `sources.{key}` names no attribute of the brief")
    return Brief(
        person=top["person"],
        world=casting["world"],
        template_version=int(casting["template_version"]),
        attributes=tuple(sources),
    )
