//! The reference's files: each page assembled from its entries, the JSON Schemas, and the index
//! (`docs/MODULE_SPEC.md` §8.1 `reference`).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use mineworld_worldpack::interactions::{Declarations, Role};
use serde_json::Value;

use super::entries::{Entries, Entry};
use super::{cli_page, markdown};

/// Which build generated a file; the banner and the `$comment` both start with it.
pub(super) const GENERATED: &str = "GENERATED by `mineworld reference`";

/// The files under the same directory that the cognition half of the reference generates from its
/// Pydantic models (`cognition/lm-controller/tools/reference.py`, step-25 §5.1, PR 25b), each with
/// what it lists. Their drift test is that half's own (`test_reference.py`); this command never writes,
/// removes or compares them, and the index links them.
pub(super) const COGNITION: [&str; 4] = [
    "cognition-toml.md",
    "schema/cognition-toml.schema.json",
    "memory-scopes.md",
    "schema/memory-scopes.schema.json",
];

/// The cognition half's pages, each with what it lists, for the index.
const COGNITION_PAGES: [(&str, &str); 2] = [
    (
        "cognition-toml.md",
        "the operator's cognition configuration, `cognition.toml` (generated from the cognition \
         package's models)",
    ),
    (
        "memory-scopes.md",
        "the memory scopes each seat's stack may name, and their parameters (generated from the \
         cognition package's models)",
    ),
];

/// Whether `path` is one of the cognition half's files ([`COGNITION`]).
pub(super) fn is_cognition(path: &str) -> bool {
    COGNITION.contains(&path)
}

/// The first line of every generated Markdown page.
pub(super) fn banner() -> String {
    format!(
        "<!-- {GENERATED} from mineworld {}. Do not edit: change the type's doc comment and run \
         `mineworld reference --out docs/reference`. -->\n",
        env!("CARGO_PKG_VERSION")
    )
}

/// Every file of the reference, by its path under the reference directory (`/`-separated).
pub(super) fn files(entries: &Entries, cli: &clap::Command) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    let pages: [(&str, &str, &str, &[Entry]); 6] = [
        (
            "world-pack.md",
            "The World Pack's own files",
            "`world.yaml`, and the fields the World Pack format itself reads in each kind of content \
             file. The other keys a content file may carry are the sections of [sections.md](sections.md).",
            &entries.world_pack,
        ),
        (
            "sections.md",
            "Sections",
            "Each section a System Pack of this build owns: the key it is written under in a content \
             file, which files may carry it, and every field it may set.",
            &entries.sections,
        ),
        (
            "configure.md",
            "World configuration",
            "Each file under `configure/` other than an Interaction List section \
             ([interaction-list.md](interaction-list.md)): the World Pack format's own, then each \
             System Pack's that takes one.",
            &entries.configure,
        ),
        (
            "interaction-list.md",
            "The Interaction List",
            "Each System Pack's section of the World's Interaction List, `configure/<pack id>.yaml`: \
             what its rules, parameters and consequences may name (`docs/MODULE_SPEC.md` §4.2 states \
             the list's rules).",
            &entries.interaction_list,
        ),
        (
            "decisions.md",
            "The decision list",
            "Which decision model drives each seat, and which memory policy each seat's controller \
             uses: the models this build installs and the parameters each takes.",
            &entries.decisions,
        ),
        (
            "pack-manifest.md",
            "Data pack manifests",
            "The package identity of a data pack, and the part of a style manifest the build checks.",
            &entries.pack_manifest,
        ),
    ];
    for (file, title, about, list) in pages {
        let mut page = header(title, about);
        if file == "interaction-list.md" {
            shared_shape(&mut page, list);
        }
        for entry in list {
            match &entry.declarations {
                Some(declarations) => {
                    markdown::brief(&mut page, entry);
                    declared(&mut page, entry, declarations);
                }
                None => markdown::entry(&mut page, entry),
            }
        }
        files.insert(file.to_owned(), finish(page));
        for entry in list {
            files.insert(
                format!("schema/{}.schema.json", entry.slug),
                schema_file(&entry.schema),
            );
        }
    }
    let mut page = header(
        "The `mineworld` command",
        "Every subcommand and argument this build's `mineworld` accepts, from its own parser. \
         `mineworld <command> --help` prints the same.",
    );
    cli_page::page(&mut page, cli);
    files.insert("cli.md".to_owned(), finish(page));
    let index = index(&files, entries);
    files.insert("README.md".to_owned(), index);
    files
}

/// A page's banner, title and opening paragraph.
fn header(title: &str, about: &str) -> String {
    format!(
        "{}\n# {title}\n\nThis reference describes the packs installed in this build of mineworld; a \
         build with other packs generates a different one (`docs/DECISIONS.md` `ARC-90`). It is \
         generated from the types that read each file, so it is never edited by hand.\n\n{about}\n\n",
        banner()
    )
}

/// A page with one newline at its end.
fn finish(page: String) -> String {
    format!("{}\n", page.trim_end())
}

/// A JSON Schema file: sorted keys, two-space indent, the generated `$comment` at its root.
fn schema_file(schema: &Value) -> String {
    let mut schema = schema.clone();
    if let Value::Object(map) = &mut schema {
        map.insert(
            "$comment".to_owned(),
            Value::String(format!(
                "{GENERATED} from mineworld {}. Do not edit.",
                env!("CARGO_PKG_VERSION")
            )),
        );
    }
    let text = serde_json::to_string_pretty(&schema).unwrap_or_default();
    format!("{text}\n")
}

/// What every Interaction List section may hold, from the first section's own schema.
fn shared_shape(page: &mut String, list: &[Entry]) {
    let Some(properties) = list
        .first()
        .and_then(|entry| entry.schema.get("properties"))
        .and_then(Value::as_object)
    else {
        return;
    };
    page.push_str("## The shape every section shares\n\nEvery key is optional.\n\n");
    page.push_str("| Key | What it holds |\n| --- | --- |\n");
    for (key, property) in properties {
        let _ = writeln!(
            page,
            "| `{key}` | {} |",
            markdown::description(property).unwrap_or("")
        );
    }
    page.push('\n');
    let entry_kinds = ["rules", "parameters", "consequences"];
    page.push_str("Each entry of a list:\n\n| Entry | Its keys |\n| --- | --- |\n");
    let mut selector = None;
    for kind in entry_kinds {
        let Some(items) = properties.get(kind).and_then(|list| list.get("items")) else {
            continue;
        };
        let _ = writeln!(
            page,
            "| `{kind}` | {} |",
            markdown::description(items).unwrap_or("")
        );
        let roles = items.get("properties").and_then(Value::as_object);
        selector = selector.or_else(|| {
            roles?
                .iter()
                .find(|(key, _)| Role::named(key).is_some())
                .and_then(|(_, role)| markdown::description(role))
                .map(str::to_owned)
        });
    }
    let roles: Vec<String> = Role::ALL
        .iter()
        .map(|role| format!("`{}`", role.name()))
        .collect();
    if let Some(selector) = selector {
        let _ = writeln!(
            page,
            "\nA role key ({}) holds a selector: {selector}",
            roles.join(", ")
        );
    }
    page.push_str(
        "\nEach pack's entry below lists the actions, roles, facts, parameters and knobs its section \
         may name; a value or key it does not list is refused. Its JSON Schema, under `schema/`, \
         states the whole shape.\n\n",
    );
}

/// What one pack's section declares: its actions, facts, parameters, knobs and reference lists.
fn declared(page: &mut String, entry: &Entry, declarations: &Declarations) {
    let _ = writeln!(page, "### Actions of {}\n", entry.title);
    page.push_str(
        "| Action | Roles a rule may name | A region may scope it |\n| --- | --- | --- |\n",
    );
    for action in declarations.actions {
        let roles: Vec<String> = action
            .roles
            .iter()
            .map(|r| format!("`{}`", r.name()))
            .collect();
        let _ = writeln!(
            page,
            "| `{}` | {} | {} |",
            action.action,
            roles.join(", "),
            if action.regional { "yes" } else { "no" }
        );
    }
    page.push('\n');
    if !declarations.facts.is_empty() {
        let _ = writeln!(page, "### Facts of {}\n", entry.title);
        page.push_str(
            "| Fact | Roles an entry may name | Audience | Narrowest audience | Biography configurable |\n\
             | --- | --- | --- | --- | --- |\n",
        );
        for fact in declarations.facts {
            let roles: Vec<String> = fact
                .roles
                .iter()
                .map(|(role, _)| format!("`{}`", role.name()))
                .collect();
            let _ = writeln!(
                page,
                "| `{}` | {} | `{}` | `{}` | {} |",
                fact.fact,
                roles.join(", "),
                word(&fact.default_audience),
                word(&fact.narrowest),
                if fact.biography_configurable {
                    "yes"
                } else {
                    "no"
                }
            );
        }
        page.push('\n');
    }
    let roles: Vec<String> = declarations
        .parameter_roles
        .iter()
        .map(|role| format!("`{}`", role.name()))
        .collect();
    let _ = writeln!(page, "### Parameters of {}\n", entry.title);
    if !roles.is_empty() {
        let _ = writeln!(page, "A parameter entry may name {}.\n", roles.join(", "));
    }
    block(page, entry, &declarations.parameters);
    if has_properties(&declarations.knobs) {
        let _ = writeln!(page, "### Knobs of {}\n", entry.title);
        page.push_str("A consequence entry may set these.\n\n");
        block(page, entry, &declarations.knobs);
    }
    let lists: Vec<String> = declarations
        .reference_lists
        .iter()
        .map(|name| format!("`{name}`"))
        .collect();
    let _ = writeln!(
        page,
        "**Reference lists** a section may `extends`: {}.\n",
        lists.join(", ")
    );
}

/// A parameter or knob block: a field table.
fn block(page: &mut String, entry: &Entry, schema: &schemars::Schema) {
    let mut schema = schema.clone().to_value();
    super::entries::first_paragraphs(&mut schema);
    markdown::shape(page, &format!("{}-block", entry.slug), &schema);
}

fn has_properties(schema: &schemars::Schema) -> bool {
    schema
        .get("properties")
        .and_then(Value::as_object)
        .is_some_and(|properties| !properties.is_empty())
}

/// A declared value as its section writes it.
fn word(value: &impl serde::Serialize) -> String {
    match serde_json::to_value(value) {
        Ok(Value::String(text)) => text,
        Ok(other) => other.to_string(),
        Err(_) => String::new(),
    }
}

/// The index: every page and every schema, generated too.
fn index(files: &BTreeMap<String, String>, entries: &Entries) -> String {
    let mut page = header(
        "Configuration reference",
        "Every field a World Pack's files may set, generated from the code that reads them. The \
         specifications state the rules (`docs/MODULE_SPEC.md` §§4.1, 4.2); these pages list the \
         fields.",
    );
    page.push_str("| Page | What it lists |\n| --- | --- |\n");
    let describe = |entries: &[Entry]| {
        entries
            .iter()
            .map(|entry| entry.title.clone())
            .collect::<Vec<_>>()
            .join(", ")
    };
    let rows = [
        ("world-pack.md", describe(&entries.world_pack)),
        ("sections.md", describe(&entries.sections)),
        ("configure.md", describe(&entries.configure)),
        ("interaction-list.md", describe(&entries.interaction_list)),
        ("decisions.md", describe(&entries.decisions)),
        ("pack-manifest.md", describe(&entries.pack_manifest)),
        (
            "cli.md",
            "every `mineworld` subcommand and argument".to_owned(),
        ),
    ];
    for (file, listed) in rows {
        let _ = writeln!(page, "| [{file}]({file}) | {listed} |");
    }
    for (file, listed) in COGNITION_PAGES {
        let _ = writeln!(page, "| [{file}]({file}) | {listed} |");
    }
    page.push_str(
        "\nThe same schemas, as JSON Schema files an editor's YAML support can read, are in \
         [`schema/`](schema/):\n\n",
    );
    let schemas = files
        .keys()
        .map(String::as_str)
        .chain(COGNITION)
        .filter(|path| path.starts_with("schema/"))
        .collect::<std::collections::BTreeSet<_>>();
    for path in schemas {
        let _ = writeln!(page, "- [`{path}`]({path})");
    }
    finish(page)
}
