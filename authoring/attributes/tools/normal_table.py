"""Generate authoring/attributes/src/sample/normal_table.rs: the standard-normal quantile at k/1000, k = 1 ... 999,
in micro-units, rounded half away from zero (pr-s30d-sampler.md section 5.6).

Run once, offline: python3 authoring/attributes/tools/normal_table.py > authoring/attributes/src/sample/normal_table.rs
The committed integer table is the authority; no run of MineWorld touches a float. Standard library only:
statistics.NormalDist().inv_cdf is Wichura's AS 241 (Applied Statistics 37, 1988).
"""

import math
import platform
import statistics


def half_away(x: float) -> int:
    return int(math.copysign(math.floor(abs(x) + 0.5), x))


def main() -> None:
    normal = statistics.NormalDist()
    values = [half_away(normal.inv_cdf(k / 1000) * 1_000_000) for k in range(1, 1000)]
    print("//! The standard-normal quantile at k/1000, k = 1 ... 999, in micro-units (generated; do not edit).")
    print("//!")
    print("//! Generated by `python3 authoring/attributes/tools/normal_table.py` with CPython "
          f"{platform.python_version()}: statistics.NormalDist().inv_cdf (Wichura's AS 241), rounded half away from")
    print("//! zero to micro-units. `Z[0]` is z(0.001).")
    print()
    print("/// `Z[k - 1]` is the quantile at `k / 1000`, in micro-units.")
    print("#[rustfmt::skip]")
    print(f"pub const Z: [i32; 999] = [")
    for start in range(0, 999, 10):
        row = ", ".join(str(v) for v in values[start:start + 10])
        print(f"    {row},")
    print("];")


if __name__ == "__main__":
    main()
